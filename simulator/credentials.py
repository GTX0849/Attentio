"""The file listing the simulated accounts, in the git-ignored `.spool/` folder."""

from pathlib import Path

from shared.config import DEMO_PASSWORD_ENV, PROJECT_ROOT
from simulator.client import DemoAccount

CREDENTIALS_PATH = PROJECT_ROOT / ".spool" / "demo-credentials.txt"


def credentials_text(accounts: tuple[DemoAccount, ...], password: str, generated: bool) -> str:
    """The file's content. The password is written only when this run made it up; a password the
    person chose themselves (CLASSPULSE_DEMO_PASSWORD) is not copied into a file."""
    shown = password if generated else f"the value of {DEMO_PASSWORD_ENV}"
    lines = [
        "ClassPulse simulated accounts (regenerated by every `python -m simulator seed`)",
        f"Password for every account below: {shown}",
        "Sign in on the dashboard with an email and this password.",
        "",
    ]
    for role in ("teacher", "student"):
        lines += [f"{a.email}  {a.role}  {a.name}" for a in accounts if a.role == role]
    return "\n".join(lines) + "\n"


def write_credentials(
    accounts: tuple[DemoAccount, ...], password: str, generated: bool, path: Path = CREDENTIALS_PATH
) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(credentials_text(accounts, password, generated), encoding="utf-8")
    return path
